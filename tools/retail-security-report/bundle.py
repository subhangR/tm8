#!/usr/bin/env python3
"""Pack the Retail Security pipeline (annual + monthly mode) into ONE copy-pasteable python file.

  python3 -P tools/retail-security-report/bundle.py [research/retail-security-2026] [out.py]

The output (default tools/retail-security-report/retail_security_report_local.py) carries the
orchestrator plus a compressed payload of scripts/*.py, build/pw/*.mjs and build/shots/list.json.
Run it anywhere with python3: it extracts ./retail-security-2026/, installs its python deps and the
Playwright Chromium if missing, and runs the stages (default: build). Raw data, screenshots and
built outputs are never bundled.
"""
import base64, io, os, sys, tarfile, zlib, datetime as dt

HERE = os.path.dirname(os.path.abspath(__file__))
