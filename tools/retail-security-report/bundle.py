def unpack(project, refresh=False):
    """Unpack scripts/ and the browser helpers into the project. A project created by an OLDER runner build is
    refreshed (its scripts replaced by this file's copy) so a re-download always runs the current code; raw/ data,
    build/ outputs and the ledger are never touched."""
    import base64, io, tarfile, zlib
    marker = os.path.join(project, ".runner-build")
    old = open(marker).read().strip() if os.path.exists(marker) else ""
    if os.path.isdir(os.path.join(project, "scripts")) and old != BUILD and not refresh:
        print(f"[setup] project was built by runner {old or 'unknown (before build stamps)'}; updating its bundled scripts to build {BUILD}", flush=True)
        refresh = True
    data = zlib.decompress(base64.b64decode(PAYLOAD))
    n = 0
    with tarfile.open(fileobj=io.BytesIO(data)) as tar:
        for m in tar.getmembers():
            dst = os.path.join(project, m.name)
            if os.path.exists(dst) and not refresh: continue
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "wb") as f: f.write(tar.extractfile(m).read())
            n += 1
    for d in ("raw", "build", "build/shots", "build/pdf", "build/site", "build/runs", "build/periods"): os.makedirs(os.path.join(project, d), exist_ok=True)
    with open(marker, "w") as f: f.write(BUILD + "\n")
    return n


def _ver_ok(exe, lo=(3, 10), hi=(3, 13)):
    try:
        out = subprocess.run([exe, "-c", "import sys;print(sys.version_info[0],sys.version_info[1])"], capture_output=True, text=True, timeout=20).stdout.split()
        v = (int(out[0]), int(out[1]))
        return v if lo <= v <= hi else None
    except Exception: return None


def ensure_venv(project, argv):
    """Run inside <project>/.venv (created on first use). Avoids Homebrew/Debian 'externally-managed-environment'
    pip refusals and keeps the laptop's own Python untouched. Re-executes this file under the venv interpreter."""
    import shutil
    if os.environ.get("RSR_IN_VENV") or sys.prefix != getattr(sys, "base_prefix", sys.prefix): return   # already in a venv
    vdir = os.path.join(project, ".venv")
    vpy = os.path.join(vdir, "Scripts", "python.exe") if os.name == "nt" else os.path.join(vdir, "bin", "python")
    if not os.path.exists(vpy):
        cands = [CONFIG["PYTHON"]] if CONFIG["PYTHON"] else []
        cands += [shutil.which(n) for n in ("python3.13", "python3.12", "python3.11", "python3.10", "python3", "python", "py")]
        bases = [c for c in dict.fromkeys(c for c in cands if c) if _ver_ok(c)]
        if not bases:
            if sys.version_info >= (3, 10): bases = [sys.executable]; print(f"[setup] note: python {sys.version_info[0]}.{sys.version_info[1]} is newer than the versions this was tested on (3.10-3.13); continuing", flush=True)
            else: print(f"[setup] python 3.10 or newer is needed (found {sys.version_info[0]}.{sys.version_info[1]})", flush=True); sys.exit(2)
        os.makedirs(project, exist_ok=True)
        for base in bases:
            print(f"[setup] creating virtual environment {vdir} with {base}", flush=True)
            r = subprocess.run([base, "-m", "venv", vdir], capture_output=True, text=True)
            if r.returncode == 0 and os.path.exists(vpy): break
            shutil.rmtree(vdir, ignore_errors=True)
            print("[setup]   venv failed: " + ((r.stderr + r.stdout).strip().splitlines() or ["?"])[0][:160], flush=True)
        if not os.path.exists(vpy):
            print("[setup] no interpreter could create a virtual environment (Debian/Ubuntu: sudo apt install python3-venv); continuing with the current python", flush=True); return
        subprocess.run([vpy, "-m", "pip", "install", "--quiet", "--upgrade", "pip"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    env_ = dict(os.environ, RSR_IN_VENV="1")
    cmd = [vpy, os.path.abspath(__file__), *argv]
    if os.name == "nt": sys.exit(subprocess.call(cmd, env=env_))
    os.execve(vpy, cmd, env_)


def _importable(dep):
    """Real import (find_spec passes for a package whose native library cannot load)."""
    r = subprocess.run([sys.executable, "-c", "import " + IMPORT_NAMES[dep]], capture_output=True, text=True)
    return r.returncode == 0, (r.stderr.strip().splitlines() or [""])[-1][:160]


def ensure_deps(project, install=True):
    missing = [d for d in PIP_DEPS if not _importable(d)[0]]
    if missing and install:
        specs = [PIP_SPECS.get(d, d) for d in missing]
        print(f"[setup] installing python packages: {' '.join(specs)}", flush=True)
        if subprocess.run([sys.executable, "-m", "pip", "--version"], capture_output=True).returncode != 0:
            subprocess.run([sys.executable, "-m", "ensurepip", "--upgrade"], capture_output=True)     # python without pip (some Linux images)
        cmd = [sys.executable, "-m", "pip", "install", "--quiet", *specs]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0 and "externally-managed" in (r.stderr + r.stdout):
            r = subprocess.run(cmd + ["--break-system-packages"], capture_output=True, text=True)
        if r.returncode != 0: print(r.stderr[-800:], flush=True)
        missing = [d for d in PIP_DEPS if not _importable(d)[0]]
    hard = [d for d in missing if d not in OPTIONAL]
    for d in missing:
        if d in OPTIONAL: print(f"[setup] {d} not usable ({_importable(d)[1]}); collectors will use plain requests", flush=True)
    if hard: print(f"[setup] still missing: {hard} -> {sys.executable} -m pip install {' '.join(PIP_SPECS.get(d, d) for d in hard)}", flush=True); sys.exit(2)
    # A browser for screenshots, the site check and the PDF: Playwright's own Chromium, else an installed Google Chrome / Edge.
    probe = [sys.executable, "-P", os.path.join(project, "scripts", "rsr_browser.py"), "probe"]
    def ok():
        try: r = subprocess.run(probe, capture_output=True, text=True, timeout=180)
        except subprocess.TimeoutExpired: return False, "probe timed out"
        used = [l.split("using ", 1)[1] for l in r.stdout.splitlines() if l.startswith("browser: using ")]
        if r.returncode == 0: return True, (used or ["Chromium"])[0]
        return False, (r.stdout.strip().splitlines() or [r.stderr.strip()[-200:]])[-1][:200]
    good, why = ok()
    if good: return summary(True, why)
    if not install: print("[setup] no browser launches: " + why, flush=True); return summary(False, why)
    print("[setup] installing Playwright Chromium (one-time download)", flush=True)
    r = subprocess.run([sys.executable, "-m", "playwright", "install", "chromium"], capture_output=True, text=True)
    if r.returncode != 0:
        msg = (r.stderr + r.stdout)
        if "does not support" in msg: print("[setup] Playwright has no Chromium build for this OS version; trying an installed Google Chrome / Edge instead", flush=True)
        else: print(msg[-500:], flush=True)
    good, why = ok()
    if good: return summary(True, why)
    print("[setup] no browser launches: " + why, flush=True)
    if sys.platform == "darwin": print("[setup] -> install Google Chrome from https://www.google.com/chrome/ (the download page serves the last version for your macOS), then run this file again: the PDF, the screenshots and the page check use it", flush=True)
    elif sys.platform.startswith("linux"): print("[setup] -> run once: sudo " + sys.executable + " -m playwright install-deps chromium   (or install Google Chrome) and run again", flush=True)
    else: print("[setup] -> install Google Chrome or Microsoft Edge and run again", flush=True)
    return summary(False, why)


def summary(browser_ok, browser_note):
    """One line a reader can check against: python, each package, transport, browser, docker, scripts build."""
    import shutil
    pk = []
    for d in PIP_DEPS:
        good, why = _importable(d)
        pk.append(d + (" OK" if good else (" FALLBACK(plain requests)" if d in OPTIONAL else " MISSING")))
    docker = "docker OK" if shutil.which("docker") else "docker -"
    br = ("browser " + browser_note + " OK") if browser_ok else "browser NONE (shots/check/pdf skipped)"
    print(f"[setup] checks: python {sys.version.split()[0]} OK · " + " · ".join(pk) + f" · {br} · {docker} · scripts build {BUILD}", flush=True)
    return browser_ok


def local_main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    C = CONFIG
    here = os.path.dirname(os.path.abspath(__file__))
    pre = argparse.ArgumentParser(add_help=False)
    pre.add_argument("--project", default=env("RSR_PROJECT", os.path.join(here, C["PROJECT"])))
    pre.add_argument("--refresh-scripts", action="store_true", default=C["REFRESH_SCRIPTS"], help="overwrite the bundled scripts in the project dir")
    pre.add_argument("--no-install", action="store_true", default=not C["INSTALL_DEPS"], help="do not pip-install missing packages or Chromium")
    pre.add_argument("--no-venv", action="store_true", default=not C["USE_VENV"], help="run with the current python instead of <project>/.venv")
    pre.add_argument("--stages", default=env("RSR_STAGES", C["STAGES"]))
    known, rest = pre.parse_known_args(argv)
    # CONFIG values become the orchestrator defaults; explicit flags in `rest` win
    defaults = ["--browser", C["BROWSER"], "--collect-minutes", str(C["COLLECT_MINUTES"])]
    if C["FORCE"] and "--force" not in rest: defaults.append("--force")
    if C["OUT"]: defaults += ["--out", C["OUT"]]
    if C["PUBLISH"] and "--publish" not in rest: defaults.append("--publish")
    if C["ARTIFACT"]: defaults += ["--artifact", C["ARTIFACT"]]
    if C["TASK"]: defaults += ["--task", C["TASK"]]
    if C["PERIOD_FROM"] and "--period-from" not in rest: defaults += ["--period-from", C["PERIOD_FROM"]]
    if C["PERIOD_TO"] and "--period-to" not in rest: defaults += ["--period-to", C["PERIOD_TO"]]
    if C["MODEL"] and "--model" not in rest: defaults += ["--model", C["MODEL"]]
    if C["NO_LLM"] and "--no-llm" not in rest: defaults.append("--no-llm")
    if C["FIRST_FROM"] and "--first-from" not in rest: defaults += ["--first-from", C["FIRST_FROM"]]
    if C["BROWSER_CHANNEL"] and "--browser-channel" not in rest: defaults += ["--browser-channel", C["BROWSER_CHANNEL"]]
    if C["ANTHROPIC_API_KEY"] and not os.environ.get("ANTHROPIC_API_KEY"): os.environ["ANTHROPIC_API_KEY"] = C["ANTHROPIC_API_KEY"]
    rest = defaults + rest
    if "-h" in argv or "--help" in argv:
        print(__doc__); print("\nEverything has a default in CONFIG at the top of this file.\nLocal-runner options:\n  --project <dir>      where to unpack/run (default <this file's folder>/retail-security-2026)\n  --refresh-scripts    overwrite bundled scripts\n  --no-install         skip pip/Chromium setup\n  --no-venv            use the current python instead of the project's own .venv\n  --stages <set|list>  monthly (default: collect the new window + build its report) | monthly-build (rebuild a window from raw/)\n                       | build (the annual report from the register) | all (re-collect since 1 Jan + annual build)\n  --period-from/--period-to YYYY-MM-DD   monthly window override (default: day after the last run .. today)\n  --no-llm / --model   monthly summaries: rule-built, or the Claude model used with ANTHROPIC_API_KEY\n  --first-from YYYY-MM-DD   where the very first window starts (default 2026-10-01)\n  --browser-channel auto|chromium|chrome|msedge   which browser renders the PDF (auto: bundled Chromium, else Google Chrome, else Edge)\nAll orchestrator options also apply (--browser, --force, --out, --publish, --artifact, --task, --collect-minutes).")
        return 0
    project = os.path.abspath(known.project)
    if not os.environ.get("RSR_IN_VENV"): print(f"[setup] runner build {BUILD}", flush=True)
    if C["USE_VENV"] and not known.no_venv: ensure_venv(project, argv)        # re-executes under <project>/.venv and never returns
    n = unpack(project, known.refresh_scripts)
    print(f"[setup] project {project} ({n} files unpacked) · python {sys.version.split()[0]} at {sys.executable}", flush=True)
    if not ensure_deps(project, install=not known.no_install):
        print("[setup] no browser: shots/check/pdf are skipped unless docker's Playwright image is present; collection, site, verify and report still run", flush=True)
    return main(["--project", project, "--stages", known.stages, *rest])


