#!/bin/bash
# One dev tm8 node for the context eval. NEVER 7778. Ports 4620-4624 only.
#
#   dev-node.sh up   <port> <db> <datadir> <build-dir> [ARM=lean|index-derived|index-authored|inherit]
#   dev-node.sh stop <port>
#   dev-node.sh status <port>
#
# `up` (idempotent): creates the DB on postgres://tm8@127.0.0.1:$CTX_EVAL_PG_PORT
# (default 5442; the utho box runs on staging PG 5443) if absent,
# migrates it with the build's chain, (re)starts the server under `env -i` with
# the ARM's env + TM8_LAUNCH_BOOTSTRAP=1 + TM8_DELIVERY_DATABASE_URL as the
# non-superuser tm8_delivery_worker (a superuser URL is refused at boot, and
# without delivery a message to a lane is stored but never pushed: the
# multi-turn family needs it), claims the owner on first run, creates the space
# (which seeds the launch-catalog teammates: Sonnet 5, Haiku 4.5, ...), the
# project and the ledger-lite fixture repo, writes <datadir>/t8 (owner CLI
# wrapper under env -i) and registers the node in $CTX_EVAL_HOME/nodes/<port>.json.
# Re-running `up` with another ARM just restarts the server under it.
#
# Env overrides: CTX_EVAL_HOME (registry root), CTX_EVAL_PG_PORT (default 5442),
# CTX_EVAL_BUILD_SHA (else <build-dir>/BUILD_SHA, else `git rev-parse` there: a
# read-only build exported without .git still records its real sha).
set -euo pipefail
CMD=${1:-}; PORT=${2:-}
EVAL_HOME=${CTX_EVAL_HOME:-/private/tmp/ctxeval}
PG_PORT=${CTX_EVAL_PG_PORT:-5442}
case "$PG_PORT" in ''|*[!0-9]*) echo "dev-node: CTX_EVAL_PG_PORT=$PG_PORT is not a port" >&2; exit 1;; esac
PG=postgres://tm8@127.0.0.1:$PG_PORT
HERE=$(cd "$(dirname "$0")" && pwd)
ARM=${ARM:-lean}
warn() { echo "dev-node: $*" >&2; }
die() { warn "$*"; exit 1; }
listen_pid() { lsof -nP -iTCP:"$1" -sTCP:LISTEN -t 2>/dev/null | head -1 || true; }

case "$CMD" in
  stop)
    [ -n "$PORT" ] || die "usage: dev-node.sh stop <port>"
    P=$(listen_pid "$PORT"); [ -n "$P" ] || { warn "nothing listens on $PORT"; exit 0; }
    kill "$P"; for i in $(seq 1 30); do [ -z "$(listen_pid "$PORT")" ] && break; sleep 0.5; done
    warn "stopped $PORT (pid $P)"; exit 0;;
  status)
    [ -n "$PORT" ] || die "usage: dev-node.sh status <port>"
    P=$(listen_pid "$PORT"); echo "port $PORT pid ${P:-none}"; cat "$EVAL_HOME/nodes/$PORT.json" 2>/dev/null || true; exit 0;;
  up) ;;
  *) die "usage: dev-node.sh up <port> <db> <datadir> <build-dir> [ARM=...] | stop <port> | status <port>";;
esac

DB=${3:-}; DATADIR=${4:-}; BUILD=${5:-}
[ -n "$PORT" ] && [ -n "$DB" ] && [ -n "$DATADIR" ] && [ -n "$BUILD" ] || die "usage: dev-node.sh up <port> <db> <datadir> <build-dir> [ARM=...]"
case "$PORT" in 4620|4621|4622|4623|4624) ;; *) die "port $PORT is not an eval port (4620-4624); 7778 is never touched";; esac
case "$DB" in tm8_eval[0-4]) ;; *) die "db $DB is not an eval db (tm8_eval0..4)";; esac
case "$ARM" in lean|index-derived|index-authored|inherit) ;; *) die "ARM=$ARM is not one of lean|index-derived|index-authored|inherit";; esac
[ -f "$BUILD/packages/server/dist/index.js" ] && [ -f "$BUILD/packages/cli/dist/index.js" ] || die "$BUILD has no server/cli dist: bun install && bun run build there first"
for d in "$DATADIR" "$EVAL_HOME"; do case "$d" in /*) ;; *) die "$d is not an absolute path";; esac; done
mkdir -p "$DATADIR" "$EVAL_HOME/nodes"
# Skill paths refuse symlinks: the datadir (and the registry home) must already be
# their own realpath. On macOS /tmp -> /private/tmp is the usual trap; on Linux /tmp
# is real, so the check is realpath, not a /tmp prefix.
for d in "$DATADIR" "$EVAL_HOME"; do
  [ "$(realpath "$d")" = "${d%/}" ] || die "$d resolves to $(realpath "$d"): use a REAL path (e.g. /private/tmp/... on macOS); skill paths refuse symlinks"
done
BUILD_SHA=${CTX_EVAL_BUILD_SHA:-$(cat "$BUILD/BUILD_SHA" 2>/dev/null || git -C "$BUILD" rev-parse HEAD 2>/dev/null || echo unknown)}
# The node runs under env -i: pick a SHELL and LANG that exist on this host (macOS
# defaults kept; Linux boxes may have no zsh and no en_US locale).
NODE_SHELL=/bin/zsh; [ -x "$NODE_SHELL" ] || NODE_SHELL=/bin/bash
NODE_LANG=en_US.UTF-8
if [ "$(uname -s)" != Darwin ] && ! locale -a 2>/dev/null | grep -qiE '^en_US\.utf-?8$'; then NODE_LANG=C.UTF-8; fi

# 1. database + migrations (the build's own chain)
if ! psql "$PG/postgres" -Atc "select 1 from pg_database where datname='$DB'" | grep -q 1; then
  psql "$PG/postgres" -qc "create database $DB"; warn "created $DB"
fi
(cd "$BUILD" && TM8_DATABASE_URL="$PG/$DB" node db/migrate.mjs up 2>&1 | tail -2 >&2)

# 2. (re)start under env -i
P=$(listen_pid "$PORT"); if [ -n "$P" ]; then kill "$P"; for i in $(seq 1 30); do [ -z "$(listen_pid "$PORT")" ] && break; sleep 0.5; done; warn "restarted $PORT for ARM=$ARM"; fi
SURFACE=minimal; INDEX=
case "$ARM" in inherit) SURFACE=inherit;; index-*) INDEX=on;; esac
cat > "$DATADIR/start.sh" <<START
#!/bin/bash
# generated by dev-node.sh: ARM=$ARM build=$BUILD_SHA
cd "$BUILD"
# USER/SHELL/LANG and the full PATH matter: a Claude lane without USER cannot read its keychain login ("Not logged in").
# CLAUDE_CODE_DISABLE_AUTO_MEMORY=1: lanes inherit it, so none is given or told to write
# project memory (DESIGN 7 (l), ruling D11); lanes.mjs's memory-dir guard stays as the backstop.
exec env -i HOME="\$HOME" USER="\$(id -un)" SHELL=$NODE_SHELL LANG=$NODE_LANG PATH="/opt/homebrew/opt/node@22/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin:\$HOME/.local/bin:\$HOME/.bun/bin" \\
  CLAUDE_CODE_DISABLE_AUTO_MEMORY=1 TM8_ENV=dev TM8_DATA_DIR="$DATADIR" TM8_PORT=$PORT TM8_BIND=127.0.0.1 \\
  TM8_DATABASE_URL="$PG/$DB" TM8_DELIVERY_DATABASE_URL="postgres://tm8_delivery_worker@127.0.0.1:$PG_PORT/$DB" TM8_LAUNCH_BOOTSTRAP=1 \\
  TM8_HARNESS_SURFACE=$SURFACE ${INDEX:+TM8_CONTEXT_INDEX=$INDEX} node packages/server/dist/index.js
START
chmod +x "$DATADIR/start.sh"
nohup "$DATADIR/start.sh" >> "$DATADIR/server.log" 2>&1 &
for i in $(seq 1 60); do curl -fsS "http://127.0.0.1:$PORT/healthz" >/dev/null 2>&1 && break; curl -fsS "http://127.0.0.1:$PORT/" >/dev/null 2>&1 && break; sleep 0.5; done
[ -n "$(listen_pid "$PORT")" ] || die "server did not come up on $PORT; see $DATADIR/server.log"

# 3. owner claim (first run only): POST /v2/auth/claim {token, username, password, displayName}
if [ ! -s "$DATADIR/owner-token" ]; then
  for i in $(seq 1 20); do [ -s "$DATADIR/setup-token" ] && break; sleep 0.5; done
  [ -s "$DATADIR/setup-token" ] || die "no setup-token in $DATADIR (node already claimed by someone else?)"
  # head must be FIRST: with `tr </dev/urandom | head`, tr takes SIGPIPE when head closes and
  # `set -o pipefail` turns that into exit 141 before the claim (C1's finding, msg 01a0d95c-15ce).
  PW=$(head -c 512 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-24)
  [ "${#PW}" -ge 16 ] || die "could not mint an owner password"
  echo "$PW" > "$DATADIR/owner-password"; chmod 600 "$DATADIR/owner-password"
  curl -fsS -X POST "http://127.0.0.1:$PORT/v2/auth/claim" -H 'content-type: application/json' \
    -d "{\"token\":\"$(cat "$DATADIR/setup-token")\",\"username\":\"owner\",\"password\":\"$PW\",\"displayName\":\"Eval Owner\"}" > "$DATADIR/claim.json"
  node -e 'const j=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));process.stdout.write(j.data.token)' "$DATADIR/claim.json" > "$DATADIR/owner-token"
  chmod 600 "$DATADIR/owner-token"; warn "claimed $PORT as owner"
fi

# 4. CLI wrapper (env -i: nothing from a lane's env can leak into it)
cat > "$DATADIR/t8" <<T8
#!/bin/bash
# owner CLI for eval node $PORT (generated by dev-node.sh). The space defaults to
# the node's registered one ($DATADIR/space-id); TM8_SPACE_ID overrides it.
SP=\${TM8_SPACE_ID:-\$(cat "$DATADIR/space-id" 2>/dev/null)}
exec env -i HOME="\$HOME" PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin" TM8_BASE_URL=http://127.0.0.1:$PORT TM8_AGENT_TOKEN="\$(cat "$DATADIR/owner-token")" \\
  \${SP:+TM8_SPACE_ID=\$SP} node "$BUILD/packages/cli/dist/index.js" "\$@"
T8
chmod +x "$DATADIR/t8"
T8="$DATADIR/t8"

# 5. space (seeds the catalog teammates; SPACE_ID=<id> reuses one), project + fixture repo
REG="$EVAL_HOME/nodes/$PORT.json"
SPACE=${SPACE_ID:-$( [ -f "$REG" ] && node -e 'const j=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));process.stdout.write(j.spaceId||"")' "$REG" || true )}
if [ -z "$SPACE" ]; then
  # an earlier `up` without a registry (or a hand-made node): reuse a space of this name
  SPACE=$("$T8" space list --limit 50 --format json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{s=s.slice(0,s.lastIndexOf("}")+1);const j=JSON.parse(s);const it=(j.page?.items||j.items||[]).find(x=>(x.title||x.name)==="ctx-eval-"+process.argv[1]);process.stdout.write(it?it.id:"")})' "$PORT" || true)
fi
if [ -z "$SPACE" ]; then
  SPACE=$("$T8" space create "ctx-eval-$PORT" --format json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{s=s.slice(0,s.lastIndexOf("}")+1);const j=JSON.parse(s);process.stdout.write(j.id||j.space?.id||j.data?.id||"")})')
  [ -n "$SPACE" ] || die "space create returned no id"
  warn "space $SPACE"
fi
export TM8_SPACE_ID="$SPACE"
echo "$SPACE" > "$DATADIR/space-id"
REPO="$DATADIR/fixture-repo"
if [ ! -d "$REPO/.git" ]; then
  mkdir -p "$REPO/src" "$REPO/test"
  cat > "$REPO/package.json" <<'PKG'
{ "name": "ledger-lite", "version": "0.1.0", "type": "module", "private": true, "scripts": { "test": "node --test" } }
PKG
  cat > "$REPO/src/ledger.js" <<'JS'
// ledger-lite: a small CSV ledger. Product rules live in the tm8 docs linked
// to each task, never here.
export function parseCsv(text) {
  const [header, ...lines] = text.trim().split('\n');
  const cols = header.split(',');
  return lines.filter(Boolean).map((line) => {
    const cells = line.split(',');
    const row = {};
    cols.forEach((c, i) => { row[c] = c === 'amount' ? Number(cells[i]) : cells[i]; });
    return row;
  });
}
JS
  cat > "$REPO/test/parse.test.js" <<'JS'
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseCsv } from '../src/ledger.js';
test('parseCsv reads amounts as numbers', () => {
  const rows = parseCsv('id,date,amount,category,merchant\n1,2026-01-02,10.50,food,Corner Deli\n');
  assert.equal(rows.length, 1);
  assert.equal(rows[0].amount, 10.5);
});
JS
  printf '# ledger-lite\n\nA small CSV ledger. Tests: `npm test` (node --test). Product rules for helpers are in the tm8 docs linked to each task.\n' > "$REPO/README.md"
  git -C "$REPO" init -q -b main
  git -C "$REPO" -c user.email=fixture@ctx-eval -c user.name=fixture add -A
  git -C "$REPO" -c user.email=fixture@ctx-eval -c user.name=fixture commit -qm 'ledger-lite fixture'
  warn "fixture repo $REPO"
fi
PROJECT=$( [ -f "$REG" ] && node -e 'const j=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));process.stdout.write(j.projectId||"")' "$REG" || true )
if [ -z "$PROJECT" ]; then
  PROJECT=$("$T8" project create "ledger-lite" --working-dir "$REPO" --repo-url none --trust trusted --format json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{s=s.slice(0,s.lastIndexOf("}")+1);const j=JSON.parse(s);process.stdout.write(j.id||j.project?.id||j.data?.id||j.data?.project?.id||"")})')
  [ -n "$PROJECT" ] || die "project create returned no id"
  "$T8" project link "$PROJECT" --space "$SPACE" --format json >/dev/null
  warn "project $PROJECT linked to $SPACE"
fi
# 6. eval teammates. #843 replaced the per-model catalog teammates the 2026-09-25
# baseline spawned ("Sonnet 5 Teammate", ...) with a role roster, and the boot pass
# soft-deletes those names (role "Launch persona") on every restart. The eval spawns
# its own copies under names the retire pass does not know, with the pre-#843 seed
# fields (role, persona "<label> via claude-code", model, tool, mode worker) so the
# teammate stays constant against the baseline. No header: the seed wrote none, and
# a header would add bytes to the index arms' teammates group. Idempotent by name.
team_names() { "$T8" entity query --kind team_member --limit 100 --format json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{s=s.slice(0,s.lastIndexOf("}")+1);const j=JSON.parse(s);for(const it of (j.page?.items||j.items||[]))console.log(it.title)})'; }
HAVE=$(team_names)
while IFS='|' read -r NAME LABEL MODEL; do
  printf '%s\n' "$HAVE" | grep -qxF "$NAME" && continue
  "$T8" entity create team_member "$NAME" --content "{\"role\":\"Launch persona\",\"identity\":\"$LABEL via claude-code\",\"model\":\"$MODEL\",\"agentTool\":\"claude-code\",\"mode\":\"worker\"}" --format json >/dev/null
  warn "teammate $NAME ($MODEL)"
done <<'EVAL_TEAMMATES'
Sonnet 5 Eval|Claude Sonnet 5|claude-sonnet-5
Haiku 4.5 Eval|Claude Haiku 4.5|claude-haiku-4-5-20251001
EVAL_TEAMMATES
TEAMMATES=$("$T8" entity query --kind team_member --limit 100 --format json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{s=s.slice(0,s.lastIndexOf("}")+1);const j=JSON.parse(s);const out={};for(const it of (j.page?.items||j.items||[]))out[it.title]=it.id;process.stdout.write(JSON.stringify(out))})')
node -e '
const [reg, port, pgPort, db, dataDir, build, arm, sha, cli, spaceId, projectId, repo, teammates] = process.argv.slice(1);
const rec = { port: Number(port), pgPort: Number(pgPort), db, dataDir, buildDir: build, buildSha: sha, arm, env: { CLAUDE_CODE_DISABLE_AUTO_MEMORY: "1", TM8_HARNESS_SURFACE: arm === "inherit" ? "inherit" : "minimal", ...(arm.startsWith("index") ? { TM8_CONTEXT_INDEX: "on" } : {}) }, cli, spaceId, projectId, repo, teammates: JSON.parse(teammates), updatedAt: new Date().toISOString() };
require("fs").writeFileSync(reg, JSON.stringify(rec, null, 2) + "\n");
' "$REG" "$PORT" "$PG_PORT" "$DB" "$DATADIR" "$BUILD" "$ARM" "$BUILD_SHA" "$T8" "$SPACE" "$PROJECT" "$REPO" "$TEAMMATES"
warn "up: port $PORT db $DB arm $ARM build $BUILD_SHA space $SPACE project $PROJECT; registry $REG"
