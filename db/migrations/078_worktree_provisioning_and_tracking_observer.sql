  add column if not exists path       text,
  add column if not exists branch     text;

comment on column public.worktree_allocations.path is
  'Server-computed checkout path, denormalised from public.worktrees so a '
  'pre-entity (state=preparing) row can still be reconciled. Design §6.1.';

