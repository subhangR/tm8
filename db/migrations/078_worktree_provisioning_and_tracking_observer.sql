-- A1. The allocation row learns where its own directory is.
--
-- 057's table carries no project, path or branch: those live on
-- `public.worktrees`, which does not exist until saga step 6. That is fine for
-- the happy path and fatal for §6 reconciliation, whose whole job is the rows
-- where step 6 never happened — a `preparing` allocation with no entity cannot
-- name the directory the reconciler is supposed to remove.
--
-- Nullable, deliberately: 057's own proof driver (db/test/worktrees.mjs) inserts
