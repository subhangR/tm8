  on public.worktree_allocations(node_id);

-- -----------------------------------------------------------------------------
-- A2. `create_worktree`, with the entity id supplied by the caller.
--
-- Design §4.4 requires the worktree id to be generated by the node BEFORE any
-- database write, because it is the allocation primary key and the allocation
-- is reserved (step 4) before the entity is created (step 6). 057's door minted
-- its own id through `internal.create_envelope`, which makes that ordering
-- impossible to honour: the saga would have to reserve under one id and create
-- under another, and the "deliberately no FK" note on the allocation table
-- would degrade from a design choice into an accident waiting to be noticed.
--
-- DROP then CREATE rather than `create or replace`: a trailing DEFAULT parameter
-- would make the old and new signatures ambiguous at the call site.
--
-- Everything else — the ledger label (`execution.spawn`, §2.7), the replay
-- binding shape, the space-projects admission check — is 057's, verbatim.
-- -----------------------------------------------------------------------------
drop function if exists public.create_worktree(uuid,uuid,text,text,text,text,uuid,text);

create function public.create_worktree(
  p_space_id uuid, p_project_id uuid, p_path text, p_branch text,
  p_base_ref text, p_base_commit_oid text, p_actor_id uuid default null,
  p_client_mutation_id text default null, p_entity_id uuid default null
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare
  replay jsonb;
  actor uuid;
  worktree_id uuid;
  activity_id uuid;
begin
  perform internal.require_replay_principal(p_client_mutation_id);
  replay := internal.ledger_replay(p_client_mutation_id, 'execution.spawn');
  if replay is not null then
    -- Security boundary: runs with ledger_replay's advisory lock HELD.
    perform internal.require_replay_principal(p_client_mutation_id);
    perform internal.require_replay_subject(
      replay #>> '{entity,space_id}', p_space_id::text, 'space');
    return replay;
  end if;
  perform internal.require_space_member(p_space_id);
  actor := internal.resolve_actor(p_actor_id, p_space_id);
  perform internal.bind_actor(actor);
  if not exists (select 1 from public.space_projects
                  where space_id = p_space_id and project_id = p_project_id) then
    raise exception 'project is not linked to this space' using errcode = '42501';
  end if;

  if p_entity_id is null then
    worktree_id := internal.create_envelope(p_space_id, 'worktree', actor, null, null);
  else
    -- The node-generated id, adopted verbatim. `create_envelope`'s insert,
    -- with `new_id()` replaced by the reservation's id and nothing else
    -- changed; the entities PK makes a collision a 23505, never a reuse.
    worktree_id := p_entity_id;
    insert into public.entities(id, space_id, kind, parent_id, position, created_by)
    values (worktree_id, p_space_id, 'worktree', null, null, actor);
  end if;

  insert into public.worktrees(entity_id, project_id, path, branch, base_ref, base_commit_oid)
  values (worktree_id, p_project_id, p_path, btrim(p_branch), p_base_ref, lower(p_base_commit_oid));
  perform internal.record_initial_version(worktree_id, actor);
  activity_id := internal.record_activity(p_space_id, worktree_id, actor, 'created',
                   null, jsonb_build_object('kind', 'worktree', 'branch', btrim(p_branch)));
  return internal.ledger_record(p_client_mutation_id, 'execution.spawn',
           internal.command_result(worktree_id, null, activity_id, array[worktree_id]));
end
$$;

-- -----------------------------------------------------------------------------
-- A3. Step 4 — reserve. Design §4.5.
--
-- Called by the node with the per-project Git lock ALREADY HELD and no ledger
-- in sight. The unique constraints on `public.worktrees` cannot help yet (that
-- row does not exist), so the allocation primary key is what turns a collision
-- into a 23505 instead of a silent reuse.
--
-- `p_cap` is the worktree cap of design §5.2 — separate from the session cap
-- because it bounds a different scarce resource (disk and .git/worktrees
-- metadata) and a worktree outlives the sessions that use it. 0 means no cap.
--
-- Counted over allocations that still HOLD DISK: preparing/ready/
-- cleanup_pending. `failed` holds nothing and is evidence only — and neither
-- does `missing`, which is precisely the state meaning "the directory is gone".
-- Counting `missing` would make every vanished checkout consume a cap slot
-- forever with no route back, since reconciliation treats `missing` as
-- terminal and nothing deletes allocation rows: a node with a cap set would
-- eventually refuse every spawn and need a manual SQL fix.
--
-- An exhausted `cleanup_pending` DOES still count, and should: that directory
-- is still on disk. Reconciliation reports it for an operator rather than
-- retrying forever.
-- -----------------------------------------------------------------------------
create or replace function public.reserve_worktree_allocation(
  p_worktree_entity_id uuid, p_space_id uuid, p_project_id uuid,
  p_node_id text, p_path text, p_branch text, p_cap integer default 0
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare live integer;
begin
  perform internal.require_space_member(p_space_id);
  if not exists (select 1 from public.space_projects
                  where space_id = p_space_id and project_id = p_project_id) then
    raise exception 'project is not linked to this space' using errcode = '42501';
  end if;
  if p_path is null or p_path not like '/%' or p_path like '%..%' then
    raise exception 'worktree path must be absolute and free of ..' using errcode = '22023';
  end if;

  if coalesce(p_cap, 0) > 0 then
    select count(*) into live from public.worktree_allocations
     where project_id = p_project_id
       and state in ('preparing','ready','cleanup_pending');
    if live >= p_cap then
      raise exception 'worktree cap reached for this project' using errcode = '53400',
        detail = 'worktree_cap';
    end if;
  end if;

  insert into public.worktree_allocations(
    worktree_entity_id, node_id, state, project_id, path, branch, attempts)
  values (p_worktree_entity_id, p_node_id, 'preparing', p_project_id, p_path, btrim(p_branch), 0);

  return jsonb_build_object('worktreeId', p_worktree_entity_id, 'state', 'preparing',
                            'path', p_path, 'branch', btrim(p_branch));
end
$$;

-- -----------------------------------------------------------------------------
-- A4. The operational state writer. Steps 5-8 and every §6.2 repair go through
--     here, so there is exactly one statement in the system that moves an
--     allocation between operational states.
--
-- It cannot touch `public.worktrees.status`: that is `update_worktree`'s alone
-- and 057's R29 guard makes an attempt a 23514 rather than a review comment.
-- The asymmetry is design §5.3's, deliberately — the entity records what was
-- DECIDED, the allocation records what has actually HAPPENED on disk.
-- -----------------------------------------------------------------------------
create or replace function public.set_worktree_allocation_state(
  p_worktree_entity_id uuid, p_state text,
  p_failure_code text default null, p_failure_detail jsonb default null,
  p_count_attempt boolean default false
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare alloc public.worktree_allocations;
begin
  perform internal.require_identity();
  if p_state not in ('preparing','ready','cleanup_pending','missing','failed') then
    raise exception 'invalid allocation state: %', p_state using errcode = '22023';
  end if;
  select * into alloc from public.worktree_allocations
   where worktree_entity_id = p_worktree_entity_id for update;
  if not found then
    raise exception 'no worktree allocation %', p_worktree_entity_id using errcode = 'P0002';
  end if;
  -- Once an entity exists the caller must be entitled to it. Before it exists
  -- there is nothing to be entitled to, and the reservation already checked
  -- membership; a bound identity is the honest gate for that window.
  if exists (select 1 from public.entities where id = p_worktree_entity_id) then
    perform internal.require_space_member(
      (select space_id from public.entities where id = p_worktree_entity_id));
  end if;

  update public.worktree_allocations
     set state = p_state,
         failure_code = case when p_state = 'failed' or p_state = 'cleanup_pending'
                             then coalesce(p_failure_code, failure_code) else null end,
         failure_detail = coalesce(p_failure_detail, failure_detail),
         attempts = attempts + (case when p_count_attempt then 1 else 0 end),
         last_reconciled_at = now()
   where worktree_entity_id = p_worktree_entity_id;

  return jsonb_build_object('worktreeId', p_worktree_entity_id, 'state', p_state);
end
$$;

-- -----------------------------------------------------------------------------
-- A5. The lease. Design §3.4 / §5.2: one write-capable live session per
--     worktree, enforced by 057's partial unique index — so contention is a
--     23505 here, which the node maps to `limit_exceeded`, never a queue and
--     never a hang.
--
-- ⚠ BOTH DOORS TAKE A SPACE CHECK, unconditionally.
--
-- A4's `require_identity()`-only gate is defensible only for the pre-entity
-- reservation window, where there is nothing yet to be entitled to. These two
-- doors have no such window: they operate on allocations whose entity exists
-- and whose lease is live. `release_worktree_lease` is the sharp one — the
-- single-writer invariant of §3.4 is enforced by a partial unique index over
-- `lease_session_id`, so clearing the lease is exactly what frees that index to
-- admit a SECOND session into the same working tree. Two agents writing one
-- checkout is real corruption, and "the worktree uuid is unguessable" is not an
-- authorization mechanism.
--
-- The space is one join away through `public.entities`; A1 denormalised
-- `project_id` onto the allocation, which makes it cheaper still.
-- -----------------------------------------------------------------------------
create or replace function internal.worktree_allocation_space(p_worktree_entity_id uuid)
returns uuid language sql stable set search_path = public, internal, pg_temp as $$
  select e.space_id from public.entities e where e.id = p_worktree_entity_id
$$;

create or replace function public.acquire_worktree_lease(
  p_worktree_entity_id uuid, p_session_id uuid
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare held uuid; alloc_space uuid;
begin
  perform internal.require_identity();
  select lease_session_id into held from public.worktree_allocations
   where worktree_entity_id = p_worktree_entity_id for update;
  if not found then
    raise exception 'no worktree allocation %', p_worktree_entity_id using errcode = 'P0002';
  end if;
  alloc_space := internal.worktree_allocation_space(p_worktree_entity_id);
  if alloc_space is null then
    -- Leasing something with no entity would be leasing a reservation, which
    -- no caller has a reason to do and the saga never does.
    raise exception 'worktree % has no entity to lease', p_worktree_entity_id using errcode = 'P0002';
  end if;
  perform internal.require_space_member(alloc_space);
  if held is not null and held <> p_session_id then
    raise exception 'worktree is already leased' using errcode = '53400', detail = 'worktree_leased';
  end if;
  update public.worktree_allocations
     set lease_session_id = p_session_id, lease_acquired_at = now()
   where worktree_entity_id = p_worktree_entity_id;
  return jsonb_build_object('worktreeId', p_worktree_entity_id, 'sessionId', p_session_id);
end
$$;

create or replace function public.release_worktree_lease(
  p_worktree_entity_id uuid
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare alloc_space uuid;
begin
  perform internal.require_identity();
  if not exists (select 1 from public.worktree_allocations
                  where worktree_entity_id = p_worktree_entity_id) then
    -- Reported rather than silently succeeding: a release that names nothing is
    -- a caller bug, and answering 'released: true' would hide it.
    raise exception 'no worktree allocation %', p_worktree_entity_id using errcode = 'P0002';
  end if;
  alloc_space := internal.worktree_allocation_space(p_worktree_entity_id);
  if alloc_space is not null then perform internal.require_space_member(alloc_space); end if;
  update public.worktree_allocations
     set lease_session_id = null, lease_acquired_at = null
   where worktree_entity_id = p_worktree_entity_id;
  return jsonb_build_object('worktreeId', p_worktree_entity_id, 'released', true);
end
$$;

-- -----------------------------------------------------------------------------
-- A6. Preflight token minting. Design §5.4 — the node runs the Git dirty and
--     unpushed probes (SQL cannot), digests the result, and writes it here;
--     `update_worktree` then refuses a delete whose token is absent, mismatched
--     or older than its 60-second TTL. This function is the write half of a
--     gate 057 already enforces.
--
-- ⚠ THIS DOOR HAS NO CALLER YET, AND THAT IS THE POINT OF THIS PARAGRAPH.
-- The node half of §5.4 — the `entities.patch` worktree arm that runs the Git
-- probes and mints the digest — is NOT in this change, so a `ready` worktree
-- cannot currently be deleted through `update_worktree` at all. That is a
-- deliberate scoping decision (see the PR), not an oversight.
--
-- What must NOT happen when someone wires it: this token is server-computed
-- from a real Git observation, or the gate it exists to close is defeated by
-- the caller it exists to constrain. A caller who can pass an arbitrary string
-- here and then present the same string to `update_worktree` has bypassed the
-- dirty/unpushed refusal entirely. The space check below bounds WHO can reach
-- the door; it does not and cannot make the token honest. Whoever lands the
-- patch arm owns that, and should read §5.4 before changing this function.
-- -----------------------------------------------------------------------------
create or replace function public.record_worktree_preflight(
  p_worktree_entity_id uuid, p_token text
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare alloc_space uuid;
begin
  perform internal.require_identity();
  if p_token is null or btrim(p_token) = '' then
    raise exception 'preflight token is required' using errcode = '22023';
  end if;
  alloc_space := internal.worktree_allocation_space(p_worktree_entity_id);
  if alloc_space is not null then perform internal.require_space_member(alloc_space); end if;
  update public.worktree_allocations
     set preflight_token = p_token, preflight_at = now()
   where worktree_entity_id = p_worktree_entity_id;
  if not found then
    raise exception 'no worktree allocation %', p_worktree_entity_id using errcode = 'P0002';
  end if;
  return jsonb_build_object('worktreeId', p_worktree_entity_id, 'preflightAt', now());
end
$$;

-- -----------------------------------------------------------------------------
-- A6b. The `in_worktree` edge, written UNDER THE WRITER TOKEN.
--
-- 052 added `in_worktree` to the origin-stamping branch and minted a
-- `worktree_manager` token for exactly this, with the stated purpose that "a
-- spawn-created association is distinguishable from a hand-drawn one". The
-- generic `public.write_edge` door sets no token, so an edge written through it
-- stamps `origin = 'user'` — which is the correct answer for a human drawing
-- the edge and the WRONG one for the provisioning saga. Going through
-- write_edge would have quietly made 052's token dead code and erased the one
-- distinction it exists to record.
--
-- Deliberately NOT recorder-owned: `in_worktree` stays an ordinarily mutable
-- association, correctable through generic edges.create/edges.delete (057:165).
-- This door changes who is recorded as having written it, not whether it can
-- ever be corrected.
-- -----------------------------------------------------------------------------
create or replace function public.link_session_worktree(
  p_session_id uuid, p_worktree_entity_id uuid
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare
  session_entity public.entities;
  edge_id uuid;
begin
  select * into session_entity from public.entities
   where id = p_session_id and deleted_at is null;
  if not found or session_entity.kind <> 'work_session' then
    raise exception 'no live work session %', p_session_id using errcode = 'P0002';
  end if;
  perform internal.require_space_member(session_entity.space_id);
  if not exists (select 1 from public.worktrees where entity_id = p_worktree_entity_id) then
    raise exception 'no worktree %', p_worktree_entity_id using errcode = 'P0002';
  end if;

  perform internal.w1_set_writer('worktree_manager');
  insert into public.edges(space_id, src_id, dst_id, type, created_by)
  values (session_entity.space_id, p_session_id, p_worktree_entity_id, 'in_worktree',
          internal.resolve_actor(null, session_entity.space_id))
  returning id into edge_id;
  perform internal.w1_set_writer('');

  return jsonb_build_object('edgeId', edge_id, 'sessionId', p_session_id,
                            'worktreeId', p_worktree_entity_id);
end
$$;

-- -----------------------------------------------------------------------------
-- A7. The reconciler's read. Design §6.1 cross-checks five sources; this
--     returns the two that live in Postgres (the allocation row and whether an
--     entity backs it), leaving Git, the filesystem and the live PTY map to the
--     node, which is the only place they can be observed.
--
-- `lease_session_status` is what turns §6.2's "lease held by a session with no
-- live PTY and a terminal status" from a guess into a fact.
-- -----------------------------------------------------------------------------
create or replace function public.node_worktree_allocations(p_node_id text)
returns table (
  worktree_entity_id uuid, project_id uuid, node_id text, state text,
  path text, branch text, lease_session_id uuid, attempts integer,
  failure_code text, entity_exists boolean, worktree_status text,
  lease_session_status text, updated_at timestamptz
) language sql security definer stable set search_path = public, internal, pg_temp as $$
  select a.worktree_entity_id, a.project_id, a.node_id, a.state,
         a.path, a.branch, a.lease_session_id, a.attempts, a.failure_code,
         (e.id is not null) as entity_exists,
         w.status as worktree_status,
         ls.status as lease_session_status,
         a.updated_at
    from public.worktree_allocations a
    left join public.entities e on e.id = a.worktree_entity_id and e.deleted_at is null
    left join public.worktrees w on w.entity_id = a.worktree_entity_id
    left join public.work_sessions ls on ls.entity_id = a.lease_session_id
   where a.node_id = p_node_id
   order by a.created_at;
$$;

