-- =============================================================================
-- 078 — Two write surfaces 057 and 006 deliberately left for the phase that is
-- now happening:
--
--   A. The worktree PROVISIONING and RECONCILIATION surface. 057 shipped
--      `worktrees` + `worktree_allocations` + the two semantic doors, and said
--      so in its own §8 comment: "Allocation writes belong to the provisioning
--      saga and reconciler, which arrive with their own (security definer)
--      surface in the spawn-integration phase; until then the table is
--      owner-writable only." This is that surface.
--
--   B. The tracking OBSERVER surface. 006 created
--      `public.tracking_refresh_requests` for "a worker with provider
--      credentials", and 017/034 shipped the enqueue door — but nothing has
--      ever drained the queue. This adds claim/complete and the two
--      fact-application doors the observer writes through.
--
-- Design oracle for A: docs/features/worktrees/WORKTREE-DESIGN.md
--   §3.2 allocation table · §4 provisioning saga · §5.1 lock ordering
--   §5.3 cleanup · §5.4 preflight · §6 startup reconciliation.
--
-- ⚠ LOCK ORDERING, restated because it is the one thing that deadlocks
-- (design §5.1, echoed at 057:238-242): every ledgered door takes
-- `internal.ledger_replay`'s advisory lock as its FIRST statement. The
-- per-project Git lock therefore lives OUTSIDE and BEFORE the ledgered
-- transaction, in the node's WorktreeManager. NOTHING in this file takes an
-- advisory lock, and the allocation doors below are deliberately UNLEDGERED —
-- allocation churn is operational truth, not a semantic command, and giving it
-- a client mutation id would invite it into the replay lock's blast radius for
-- no benefit.
--
-- ⚠ NO SNAPSHOT TRIGGER is added to `worktree_allocations` here, and none may
-- ever be: 057's §3 header makes "a write here is mechanically incapable of
-- bumping entities.version" a structural guarantee the memories lane depends
-- on (MEMO-WORKTREE-SEAM-ANSWERS.md W3).
-- =============================================================================

