-- -----------------------------------------------------------------------------
-- B1. A claimed row needs to say WHEN it was claimed, or a node that dies
--     mid-fetch strands its rows in 'running' forever with nothing able to tell
--     that apart from a slow fetch.
-- -----------------------------------------------------------------------------
alter table public.tracking_refresh_requests
  add column if not exists started_at timestamptz,
  add column if not exists attempts   integer not null default 0;

-- -----------------------------------------------------------------------------
-- B2. `fetched_at` is an OBSERVATION, not content — and the difference matters
--     because 017:54 versions `pull_requests` on every UPDATE.
--
-- Without this, a poller doing its job (recording that it looked, and found
-- nothing new) would bump `entities.version` on every tick, and every staleness
-- signal in the system — the thing versioning exists for — would go off
-- permanently for every tracked PR. The observer would be a version-churn
-- machine wearing a freshness costume.
--
-- So: the snapshot triggers are narrowed to the columns that carry meaning. A
-- state change still versions. A refresh that changed nothing does not. This
-- replaces 017's triggers by name; the function they call is untouched.
--
-- (`internal.snapshot_entity_version` already short-circuits on
-- `to_jsonb(new) - 'updated_at' = to_jsonb(old) - 'updated_at'` at 001:1138 —
-- it subtracts `updated_at` but NOT `fetched_at`, which is exactly why that
-- guard does not save us here and this narrowing is load-bearing rather than
-- decorative.)
--
-- ⚠ INVARIANT, AND NOTHING BUT THIS COMMENT AND ONE TEST ENFORCES IT:
--
--   each WHEN list below must equal its table's CONTENT columns —
--   every column except entity_id, space_id, created_at, updated_at, fetched_at.
--
-- Add a column to `pull_requests` or `commits` and forget this file, and that
-- column never bumps `entities.version` again, for the life of the schema. No
-- migration errors, no test fails, and every staleness signal for that field is
-- silently dead. `db/test/worktree-provisioning.mjs` diffs these lists against
-- `information_schema.columns` for exactly that reason — if you are here
-- because that test went red, it is telling you to add your column to the WHEN
-- list, not to relax the test.
-- -----------------------------------------------------------------------------
drop trigger if exists pull_requests_w2_snapshot_version on public.pull_requests;
create trigger pull_requests_w2_snapshot_version after update on public.pull_requests
for each row when (
  new.provider is distinct from old.provider or new.url    is distinct from old.url
  or new.repo  is distinct from old.repo     or new.number is distinct from old.number
  or new.title is distinct from old.title    or new.state  is distinct from old.state
  or new.head_sha is distinct from old.head_sha
) execute function internal.snapshot_entity_version();

drop trigger if exists commits_w2_snapshot_version on public.commits;
create trigger commits_w2_snapshot_version after update on public.commits
for each row when (
  new.provider is distinct from old.provider or new.url    is distinct from old.url
  or new.repo  is distinct from old.repo     or new.sha    is distinct from old.sha
  or new.message is distinct from old.message or new.author is distinct from old.author
  or new.committed_at is distinct from old.committed_at
) execute function internal.snapshot_entity_version();

-- -----------------------------------------------------------------------------
-- B3. Claim. `for update skip locked` is what makes this safe to call from more
--     than one observer without a distributed lock: two claimers take disjoint
--     rows or one takes none, never the same row twice.
--
-- Stale 'running' rows are returned to the queue in the same statement, bounded
-- by `p_stale_after_seconds`. That is the only reason B1's `started_at` exists.
--
-- security definer, and READ-ONLY of nothing: 008 grants tm8_app select on this
-- table but no update, which is correct — the queue is not a client surface.
--
-- ⚠ THE CLAIM PREDICATE MUST MATCH THE APPLY DOORS' PREDICATE.
--
-- `apply_pull_request_facts` and `apply_commit_facts` call
-- `require_space_member(row.space_id)`, which has no node-admin bypass. If this
-- door claimed rows for spaces the caller is not in, every such row would be
-- claimed, fail 42501 on apply, and — being oldest by `created_at` — be
-- reclaimed and fail identically on every subsequent tick. One unreachable row
-- would wedge the whole queue permanently. So the claim is scoped to the
-- caller's memberships, and the two doors now agree about who may act.
--
-- `p_max_attempts` is the second half of that guarantee: a row that keeps
-- failing is retired rather than retried forever. The `attempts` column existed
-- and was incremented but read by nobody, which made it decoration.
-- -----------------------------------------------------------------------------
create or replace function public.claim_tracking_refresh(
  p_limit integer default 10, p_stale_after_seconds integer default 600,
  p_max_attempts integer default 5
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare claimed jsonb;
begin
  perform internal.require_identity();

  update public.tracking_refresh_requests
     set status = 'queued', started_at = null
   where status = 'running'
     and started_at is not null
     and started_at < now() - make_interval(secs => greatest(p_stale_after_seconds, 1));

  -- Retire the rows that have burned their budget. Recorded as `failed` with a
  -- reason rather than left queued, so an operator sees a terminal row instead
  -- of a tick that mysteriously never finishes.
  update public.tracking_refresh_requests
     set status = 'failed',
         error = coalesce(error, '') ||
                 case when coalesce(error, '') = '' then '' else '; ' end ||
                 'retired after ' || attempts || ' attempts',
         completed_at = now()
   where status = 'queued'
     and attempts >= greatest(coalesce(p_max_attempts, 5), 1);

  with picked as (
    select id from public.tracking_refresh_requests r
     where r.status = 'queued'
       -- Same entitlement the apply doors enforce. Claiming what we could never
       -- apply is what turns one bad row into a permanent wedge.
       and internal.is_space_member(r.space_id)
     order by r.created_at
     limit greatest(coalesce(p_limit, 10), 1)
     for update skip locked
  ), taken as (
    update public.tracking_refresh_requests r
       set status = 'running', started_at = now(), attempts = r.attempts + 1
      from picked
     where r.id = picked.id
     returning r.id, r.space_id, r.entity_ids, r.attempts
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'requestId', t.id, 'spaceId', t.space_id, 'attempts', t.attempts,
           'targets', coalesce((
             select jsonb_agg(jsonb_build_object(
                      'entityId', e.id, 'kind', e.kind,
                      'provider', coalesce(pr.provider, c.provider),
                      'repo',     coalesce(pr.repo, c.repo),
                      'number',   pr.number,
                      'sha',      c.sha))
               from public.entities e
               left join public.pull_requests pr on pr.entity_id = e.id
               left join public.commits c        on c.entity_id  = e.id
              where e.space_id = t.space_id
                and e.deleted_at is null
                and e.kind in ('pull_request','commit')
                -- An empty/absent entity_ids means "everything tracked in this
                -- space", which is what 017's door accepts and records.
                and (t.entity_ids is null or cardinality(t.entity_ids) = 0
                     or e.id = any(t.entity_ids))
           ), '[]'::jsonb))), '[]'::jsonb)
    into claimed
    from taken t;

  return jsonb_build_object('claimed', claimed);
end
$$;

-- `p_status` exists so PARTIAL SUCCESS CAN BE TOLD THE TRUTH.
--
-- Deriving the status from `p_error` alone forces a lie in the common case: a
-- request naming ten PRs where one 404s has persisted nine real facts, and
-- recording it as `failed` says the opposite. The observer decides — `failed`
-- only when nothing was learned — and `error` carries the per-target problems
-- eitherway, so a partial result is visible rather than averaged away.
-- (`006:165`'s CHECK has no `partial`, and widening a shipped constraint to
-- gain a fourth word is not worth it when `completed` + a populated `error`
-- already says it.)
create or replace function public.complete_tracking_refresh(
  p_request_id uuid, p_error text default null, p_status text default null
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare final_status text;
begin
  perform internal.require_identity();
  final_status := coalesce(p_status, case when p_error is null then 'completed' else 'failed' end);
  if final_status not in ('completed','failed') then
    raise exception 'invalid tracking refresh status: %', final_status using errcode = '22023';
  end if;
  update public.tracking_refresh_requests
     set status = final_status,
         error = p_error,
         completed_at = now()
   where id = p_request_id;
  if not found then
    raise exception 'no tracking refresh request %', p_request_id using errcode = 'P0002';
  end if;
  return jsonb_build_object('requestId', p_request_id, 'status', final_status);
end
$$;

-- -----------------------------------------------------------------------------
-- B4. Fact application. The observer holds provider credentials (S15 keeps them
--     out of Postgres) and hands back only what it read.
--
-- A NULL argument means "the provider did not tell me", and leaves the stored
-- value alone — the difference between an unknown and an erasure. `fetched_at`
-- is stamped either way, because "I looked and learned nothing" is itself a
-- fact worth recording, and B2 is what makes recording it free.
-- -----------------------------------------------------------------------------
create or replace function public.apply_pull_request_facts(
  p_entity_id uuid, p_title text default null, p_state text default null,
  p_head_sha text default null
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare row public.pull_requests;
begin
  perform internal.require_identity();
  select * into row from public.pull_requests where entity_id = p_entity_id for update;
  if not found then
    raise exception 'no pull request %', p_entity_id using errcode = 'P0002';
  end if;
  perform internal.require_space_member(row.space_id);
  if p_state is not null and p_state not in ('open','merged','closed','draft') then
    raise exception 'invalid pull request state: %', p_state using errcode = '22023';
  end if;

  update public.pull_requests
     set title      = coalesce(p_title, title),
         state      = coalesce(p_state, state),
         head_sha   = coalesce(p_head_sha, head_sha),
         fetched_at = now(),
         updated_at = now()
   where entity_id = p_entity_id;

  return jsonb_build_object('entityId', p_entity_id, 'state', coalesce(p_state, row.state),
                            'changed', (coalesce(p_title, row.title) is distinct from row.title
                                     or coalesce(p_state, row.state) is distinct from row.state
                                     or coalesce(p_head_sha, row.head_sha) is distinct from row.head_sha));
end
$$;

create or replace function public.apply_commit_facts(
  p_entity_id uuid, p_message text default null, p_author text default null,
  p_committed_at timestamptz default null, p_url text default null
) returns jsonb language plpgsql security definer set search_path = public, internal, pg_temp as $$
declare row public.commits;
begin
  perform internal.require_identity();
  select * into row from public.commits where entity_id = p_entity_id for update;
  if not found then
    raise exception 'no commit %', p_entity_id using errcode = 'P0002';
  end if;
  perform internal.require_space_member(row.space_id);

  update public.commits
     set message      = coalesce(p_message, message),
         author       = coalesce(p_author, author),
         committed_at = coalesce(p_committed_at, committed_at),
         url          = coalesce(p_url, url),
         fetched_at   = now(),
         updated_at   = now()
   where entity_id = p_entity_id;

  return jsonb_build_object('entityId', p_entity_id,
                            'changed', (coalesce(p_message, row.message) is distinct from row.message
                                     or coalesce(p_author, row.author) is distinct from row.author));
end
$$;

