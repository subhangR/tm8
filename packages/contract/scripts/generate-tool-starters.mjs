#!/usr/bin/env node
/**
 * Writes `src/tool-starters.data.ts` from the starter tools in `examples/tools/`.
 *
 * Each starter is one directory: `tool.sh` (bash) or `tool.py` (python) is the
 * source, `spec.json` is exactly what `tm8 tool create --spec` accepts, and
 * `starter.json` carries what a spec cannot (description and the selection
 * header). Those files stay the single source of truth; the generated module
 * only lets the UI and the CLI read them without a repository checkout.
 *
 *   node packages/contract/scripts/generate-tool-starters.mjs          write
 *   node packages/contract/scripts/generate-tool-starters.mjs --check  exit 1 on drift
 *
 * `test/tool-starters.test.ts` runs the same comparison, so CI fails on drift.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const CONTRACT_ROOT = join(HERE, '..');
export const EXAMPLES_ROOT = join(CONTRACT_ROOT, '..', '..', 'examples', 'tools');
export const DATA_MODULE = join(CONTRACT_ROOT, 'src', 'tool-starters.data.ts');

const SOURCES = [['tool.sh', 'bash'], ['tool.py', 'python']];
const SPEC_KEYS = ['inputs', 'help', 'tm8Access', 'timeoutSeconds'];
const STARTER_KEYS = ['description', 'whenToUse', 'summary'];

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function exactKeys(value, keys, path) {
  const actual = Object.keys(value).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...keys].sort())) {
    throw new Error(`${path} must hold exactly ${keys.join(', ')}; found ${actual.join(', ')}`);
  }
}

/** Every directory under `examplesRoot` with a `spec.json`, as a starter record, sorted by name. */
export function readToolStarters(examplesRoot = EXAMPLES_ROOT) {
  return readdirSync(examplesRoot)
    .filter((name) => statSync(join(examplesRoot, name)).isDirectory() && existsSync(join(examplesRoot, name, 'spec.json')))
    .sort()
    .map((name) => {
      const dir = join(examplesRoot, name);
      const found = SOURCES.filter(([file]) => existsSync(join(dir, file)));
      if (found.length !== 1) throw new Error(`${dir} needs exactly one of ${SOURCES.map(([file]) => file).join(' or ')}`);
      const [[file, runtime]] = found;
      const spec = readJson(join(dir, 'spec.json'));
      exactKeys(spec, SPEC_KEYS, join(dir, 'spec.json'));
      const starter = readJson(join(dir, 'starter.json'));
      exactKeys(starter, STARTER_KEYS, join(dir, 'starter.json'));
      return {
        name,
        runtime,
        description: starter.description,
        source: readFileSync(join(dir, file), 'utf8'),
        spec: { inputs: spec.inputs, help: spec.help, tm8Access: spec.tm8Access, timeoutSeconds: spec.timeoutSeconds },
        whenToUse: starter.whenToUse,
        summary: starter.summary,
      };
    });
}

/** The generated module's exact text for `starters`. */
export function renderToolStarterData(starters) {
  return [
    '// GENERATED by packages/contract/scripts/generate-tool-starters.mjs from',
    '// examples/tools/<name>/{tool.sh|tool.py,spec.json,starter.json}. Do not edit:',
    '// change the example, then re-run the script (test/tool-starters.test.ts fails on drift).',
    "import type { ToolStarter } from './tool-starters.js';",
    '',
    `export const TOOL_STARTER_DATA: readonly ToolStarter[] = ${JSON.stringify(starters, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderToolStarterData(readToolStarters());
  const current = existsSync(DATA_MODULE) ? readFileSync(DATA_MODULE, 'utf8') : '';
  const target = relative(process.cwd(), DATA_MODULE);
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error(`${target} is out of date with examples/tools; run node packages/contract/scripts/generate-tool-starters.mjs`);
      process.exit(1);
    }
    console.log(`${target} is up to date`);
  } else if (current === text) {
    console.log(`${target} is up to date`);
  } else {
    writeFileSync(DATA_MODULE, text);
    console.log(`wrote ${target}`);
  }
}
