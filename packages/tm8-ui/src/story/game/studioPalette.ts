export function readStudioPalette(): Record<keyof typeof TOKENS, string> {
  const style = typeof document === 'undefined' ? undefined
    : document.defaultView?.getComputedStyle(document.documentElement);
  return Object.fromEntries(Object.entries(TOKENS).map(([key, [token, fallback]]) =>
    [key, style?.getPropertyValue(token).trim() || fallback],
  )) as Record<keyof typeof TOKENS, string>;
}
